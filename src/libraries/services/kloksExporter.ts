/**
 * @file kloksExporter.ts
 * @description KLOKS Artifact Generator & Promotion Workflow (§19 & §20 of IMPLEMENTATION-SPEC.md).
 * Compiles SERVICE_IR into authentic KLOKS package files (source, manifest, tests, types).
 */

import type { ServiceDocument } from '../types/serviceIR';
import { compileServicePipelineCode } from './serviceCodeCompiler';

export interface KloksGeneratedArtifact {
  packageName: string;
  files: {
    path: string;
    content: string;
    type: 'source' | 'manifest' | 'test' | 'config' | 'types';
  }[];
  manifest: Record<string, unknown>;
  changeSummary: string;
  contractDiff: {
    addedSymbols: string[];
    changedSignatures: string[];
    versionRecommendation: 'PATCH' | 'MINOR' | 'MAJOR';
  };
}

export function generateKloksArtifact(doc: ServiceDocument): KloksGeneratedArtifact {
  const serviceSlug = doc.service.name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  const packageName = `@ultrst-armada/kloks-${serviceSlug}`;
  const serviceClassName = doc.service.name.replace(/[^a-zA-Z0-9]/g, '');

  // 1. package.json
  const packageJson = JSON.stringify(
    {
      name: packageName,
      version: doc.service.version || '1.0.0',
      description: doc.service.description || 'Kult cultivated backend service artifact',
      type: 'module',
      main: './dist/index.js',
      types: './dist/index.d.ts',
      exports: {
        '.': {
          types: './dist/index.d.ts',
          import: './dist/index.js',
          default: './dist/index.js',
        },
      },
      dependencies: {
        '@ultrst-armada/krnl': '^1.0.2',
        '@ultrst-armada/kloks': '^1.5.2',
      },
      devDependencies: {
        typescript: '^5.7.3',
        vitest: '^3.1.0',
      },
    },
    null,
    2
  );

  // 2. kloks.manifest.json
  const manifestJson = JSON.stringify(
    {
      $schema: 'https://ultrst.org/schemas/kloks.manifest.v1.json',
      serviceId: doc.service.id,
      name: doc.service.name,
      version: doc.service.version || '1.0.0',
      category: 'services',
      authority: 'KULT_ENGINE',
      runtime: 'krnlts',
      entrypoint: './dist/index.js',
      contractFingerprint: `kloks_sig_${Date.now().toString(36)}`,
      inputs: doc.service.inputPorts,
      outputs: doc.service.outputPorts,
      nodeCount: doc.nodes.length,
      edgeCount: doc.edges.length,
      hasUISchema: Boolean(doc.uiSchema),
      uiSchema: doc.uiSchema,
    },
    null,
    2
  );

  // 3. src/index.ts (Compiled executable service pipeline)
  const pipelineCode = compileServicePipelineCode(doc);
  const sourceTs = `/**
 * @file index.ts
 * @service ${doc.service.name} (${doc.service.id})
 * @generated By Kult Engine from SERVICE_IR
 */

import { createService, createServiceDefinition, IService } from '@ultrst-armada/krnl';
import { ServiceAFacade, ServiceBFacade } from '@ultrst-armada/kloks/services';
import { toKebabCase } from '@ultrst-armada/kloks/functions';

export const ${serviceClassName}Definition = createServiceDefinition({
  id: '${doc.service.id}',
  name: '${doc.service.name}',
  version: '${doc.service.version || '1.0.0'}',
  operations: {
    execute: {
      id: '${doc.service.id}.execute',
      name: 'execute',
      handler: async (inputs: any) => {
${pipelineCode}
      },
    },
  },
});

export const ${serviceClassName}Service = createService(${serviceClassName}Definition);
export default ${serviceClassName}Service;
`;

  // 4. tests/service.test.ts
  const testCasesCode = doc.tests
    .map(
      (t) => `  it('${t.name}', async () => {
    await ${serviceClassName}Service.start();
    const res = await ${serviceClassName}Service.call('execute', ${JSON.stringify(t.input)});
    expect(res).toBeDefined();
${t.assertions
  .map(
    (a) =>
      `    expect(res['${a.port}']).${a.operator === 'defined' ? 'toBeDefined()' : a.operator === 'greaterThan' ? `toBeGreaterThan(${a.value})` : `toEqual(${JSON.stringify(a.value)})`};`
  )
  .join('\n')}
  });`
    )
    .join('\n\n');

  const testsTs = `import { describe, it, expect } from 'vitest';
import { ${serviceClassName}Service } from '../src/index';

describe('${doc.service.name} Authoritative Test Suite', () => {
${testCasesCode || `  it('should initialize and execute without errors', async () => {\n    expect(${serviceClassName}Service).toBeDefined();\n  });`}
});
`;

  // 5. dist/index.d.ts
  const typesDts = `import { IService, ServiceDefinition } from '@ultrst-armada/krnl';
export declare const ${serviceClassName}Definition: ServiceDefinition;
export declare const ${serviceClassName}Service: IService;
export default ${serviceClassName}Service;
`;

  return {
    packageName,
    files: [
      { path: 'package.json', content: packageJson, type: 'config' },
      { path: 'kloks.manifest.json', content: manifestJson, type: 'manifest' },
      { path: 'src/index.ts', content: sourceTs, type: 'source' },
      { path: 'tests/service.test.ts', content: testsTs, type: 'test' },
      { path: 'dist/index.d.ts', content: typesDts, type: 'types' },
    ],
    manifest: JSON.parse(manifestJson),
    changeSummary: `Promoting ${doc.service.name} v${doc.service.version} (${doc.nodes.length} nodes, ${doc.edges.length} wires, ${doc.tests.length} tests) to KLOKS.`,
    contractDiff: {
      addedSymbols: [`${serviceClassName}Service`, `${serviceClassName}Definition`],
      changedSignatures: [],
      versionRecommendation: 'MINOR',
    },
  };
}
